import 'dart:convert';
import '../../domain/entities/enums.dart';
import '../../domain/entities/legal_entities.dart';

/// Comprehensive export service that bundles all 8 PromptWars deliverables
/// into production-ready Markdown, JSON, and printable HTML formats.
class ExportService {
  /// Generates a comprehensive Markdown report of all intelligence deliverables.
  static String generateMarkdownReport(LegalDocument doc) {
    final buffer = StringBuffer();
    final now = DateTime.now();

    buffer.writeln('# LegalLens AI — Complete Legal Document Intelligence Report');
    buffer.writeln('**Document Title:** ${doc.fileName}');
    buffer.writeln('**Document Type:** ${doc.snapshot.documentType}');
    buffer.writeln('**Generated:** ${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')} ${now.hour.toString().padLeft(2, '0')}:${now.minute.toString().padLeft(2, '0')}');
    buffer.writeln('**Complexity Score:** ${doc.snapshot.complexity.name.toUpperCase()}');
    buffer.writeln('**Overall Attention Level:** ${doc.snapshot.attentionLevel.name.toUpperCase()}');
    buffer.writeln();
    buffer.writeln('> **IMPORTANT LEGAL INFORMATION DISCLAIMER:**');
    buffer.writeln('> This document was generated by LegalLens AI for informational and document preparation purposes only. It does NOT constitute legal advice and does NOT replace consultation with a qualified, licensed legal professional.');
    buffer.writeln();
    buffer.writeln('---');
    buffer.writeln();

    // 1. Executive Snapshot
    buffer.writeln('## 1. Executive Snapshot & Summary');
    buffer.writeln(doc.snapshot.executiveSummary);
    buffer.writeln();
    buffer.writeln('- **Total Identified Clauses:** ${doc.snapshot.totalClauses}');
    buffer.writeln('- **High Attention Areas:** ${doc.snapshot.highAttentionCount}');
    buffer.writeln('- **Review Recommended Areas:** ${doc.snapshot.reviewCount}');
    buffer.writeln('- **Standard Informational Areas:** ${doc.snapshot.informationalCount}');
    buffer.writeln();

    // 2. Possible Strategic Options & Next Steps
    buffer.writeln('## 2. Possible Strategic Options & Next Steps');
    for (int i = 0; i < doc.options.length; i++) {
      final opt = doc.options[i];
      buffer.writeln('### Option ${i + 1}: ${opt.title} (${opt.category})');
      buffer.writeln('**Risk Profile:** ${opt.riskProfile.name.toUpperCase()}');
      buffer.writeln(opt.summary);
      buffer.writeln();
      buffer.writeln('**Pros:**');
      for (final p in opt.pros) {
        buffer.writeln('- $p');
      }
      buffer.writeln('**Cons:**');
      for (final c in opt.cons) {
        buffer.writeln('- $c');
      }
      buffer.writeln();
      buffer.writeln('**Actionable Next Steps:**');
      for (final s in opt.actionableSteps) {
        buffer.writeln('- [ ] [${s.priority}] **${s.title}:** ${s.description}');
      }
      if (opt.suggestedDraftLanguage.isNotEmpty) {
        buffer.writeln();
        buffer.writeln('**Suggested Draft Language / Redline Snippet:**');
        buffer.writeln('```');
        buffer.writeln(opt.suggestedDraftLanguage);
        buffer.writeln('```');
      }
      buffer.writeln();
    }
    buffer.writeln('---');
    buffer.writeln();

    // 3. Clause Intelligence (15 Categories)
    buffer.writeln('## 3. Clause Intelligence & Plain-Language Explanations');
    for (final clause in doc.clauses) {
      buffer.writeln('### ${clause.title} [${clause.category.toUpperCase()}] — ${clause.importance.name.toUpperCase()}');
      buffer.writeln('**Plain English:** ${clause.plainLanguageExplanation}');
      buffer.writeln('**Why It Matters:** ${clause.whyItMatters}');
      if (clause.potentialConcern.isNotEmpty) {
        buffer.writeln('**Potential Concern:** ${clause.potentialConcern}');
      }
      buffer.writeln('**Recommended Review:** ${clause.recommendedReview}');
      buffer.writeln();
      buffer.writeln('**Original Verbatim Contract Text:**');
      buffer.writeln('> ${clause.originalText.replaceAll('\n', '\n> ')}');
      buffer.writeln();
    }
    buffer.writeln('---');
    buffer.writeln();

    // 4. Tri-Partitioned Obligations
    buffer.writeln('## 4. Responsibility Breakdown (Obligations)');
    final yourObs = doc.obligations.where((o) => o.party == ObligationParty.your).toList();
    final otherObs = doc.obligations.where((o) => o.party == ObligationParty.otherParty).toList();
    final sharedObs = doc.obligations.where((o) => o.party == ObligationParty.shared).toList();

    buffer.writeln('### Your Responsibilities (${yourObs.length})');
    for (final o in yourObs) {
      buffer.writeln('- [ ] ${o.description} *(Source: ${o.sourceClause})*');
    }
    buffer.writeln();

    buffer.writeln('### Other Party Responsibilities (${otherObs.length})');
    for (final o in otherObs) {
      buffer.writeln('- [ ] ${o.description} *(Source: ${o.sourceClause})*');
    }
    buffer.writeln();

    buffer.writeln('### Shared / Mutual Duties (${sharedObs.length})');
    for (final o in sharedObs) {
      buffer.writeln('- [ ] ${o.description} *(Source: ${o.sourceClause})*');
    }
    buffer.writeln();
    buffer.writeln('---');
    buffer.writeln();

    // 5. Important Dates & Timeline
    buffer.writeln('## 5. Important Dates & Milestone Timeline');
    if (doc.dates.isEmpty) {
      buffer.writeln('No specific timeline dates detected in document.');
    } else {
      for (final date in doc.dates) {
        buffer.writeln('- **${date.title}** (${date.type}): ${date.dateString} — *${date.sourceSnippet}*');
      }
    }
    buffer.writeln();
    buffer.writeln('---');
    buffer.writeln();

    // 6. Risk & Attention Radar (6 Categories)
    buffer.writeln('## 6. Risk & Attention Radar (6 Categories)');
    for (final r in doc.risks) {
      buffer.writeln('### ${r.category.name.toUpperCase()} — ${r.attentionLevel.name.toUpperCase()} (Confidence: ${r.confidence.name})');
      buffer.writeln('**Finding:** ${r.explanation}');
      buffer.writeln('**Safe Advisory Recommendation:** ${r.recommendedAction}');
      buffer.writeln('**Source:** ${r.relevantClause}');
      buffer.writeln();
    }
    buffer.writeln('---');
    buffer.writeln();

    // 7. Action Center: "Before You Sign" Checklist
    buffer.writeln('## 7. Action Center: "Before You Sign" Preparation Checklist');
    for (final item in doc.checklist) {
      buffer.writeln('- [${item.isChecked ? "x" : " "}] **[${item.category}]** ${item.title}');
    }
    buffer.writeln();
    buffer.writeln('---');
    buffer.writeln();

    // 8. Questions for a Legal Professional
    buffer.writeln('## 8. Personalized Questions for a Legal Professional');
    for (int i = 0; i < doc.lawyerQuestions.length; i++) {
      final q = doc.lawyerQuestions[i];
      buffer.writeln('**${i + 1}. ${q.question}**');
      buffer.writeln('- *Category:* ${q.category}');
      buffer.writeln('- *Context:* ${q.contextReason}');
      buffer.writeln('- *Reference:* ${q.sourceClause}');
      buffer.writeln();
    }

    return buffer.toString();
  }

  /// Exports the complete document intelligence bundle as structured JSON.
  static String generateJsonReport(LegalDocument doc) {
    const encoder = JsonEncoder.withIndent('  ');
    return encoder.convert(doc.toJson());
  }
}
